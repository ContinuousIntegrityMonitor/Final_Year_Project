"""Seed skill corpus: checksummed manifest and scripted runs (T-05).

corpora/skills/MANIFEST.json lists every corpus skill with a label (benign or suspicious),
the helper runs with their scripted arguments, and a checksum for every file. The label,
note and runs are written by hand; the checksums are regenerated by `update_manifest`.

The suspicious skills are inert stand-ins: they show the behaviour a detector must notice
(egress, a process left behind, hidden code unpacked and run) without doing harm.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from cim.common.schema.skills import SkillFile
from cim.skills.digest import hash_files, tree_digest
from cim.skills.runner import RunResult, Skill, discover_skills, run_script
from cim.skills.scoped import ScopedRunResult, run_script_scoped

MANIFEST_NAME = "MANIFEST.json"
MANIFEST_VERSION = 1
LABELS = ("benign", "suspicious")
UNLABELLED = "unlabelled"


@dataclass(frozen=True)
class CorpusRun:
    """One scripted helper invocation: script path relative to the skill, plus arguments."""

    script: str
    args: tuple[str, ...] = ()


@dataclass(frozen=True)
class CorpusSkill:
    skill_id: str
    label: str
    note: str
    runs: tuple[CorpusRun, ...]
    tree_digest: str
    files: tuple[SkillFile, ...]


@dataclass(frozen=True)
class CorpusRunResult:
    skill_id: str
    label: str
    run: CorpusRun
    result: RunResult
    scoped: ScopedRunResult | None  # set when the run was made inside a cgroup scope


def default_root() -> Path:
    """corpora/skills in this repository."""
    for parent in Path(__file__).resolve().parents:
        if (parent / "pyproject.toml").is_file():
            return parent / "corpora" / "skills"
    raise FileNotFoundError("pyproject.toml not found above src/cim/skills/corpus.py")


def load_manifest(root: Path) -> dict[str, CorpusSkill]:
    data = json.loads((root / MANIFEST_NAME).read_text(encoding="utf-8"))
    if data.get("version") != MANIFEST_VERSION:
        raise ValueError(f"unsupported corpus manifest version: {data.get('version')!r}")
    skills: dict[str, CorpusSkill] = {}
    for skill_id, entry in data["skills"].items():
        skills[skill_id] = CorpusSkill(
            skill_id=skill_id,
            label=entry["label"],
            note=entry.get("note", ""),
            runs=tuple(
                CorpusRun(run["script"], tuple(run.get("args", ()))) for run in entry["runs"]
            ),
            tree_digest=entry["tree_digest"],
            files=tuple(SkillFile.model_validate(item) for item in entry["files"]),
        )
    return skills


def _helper_paths(skill: Skill) -> list[str]:
    return [script.relative_to(skill.path).as_posix() for script in skill.helper_scripts]


def update_manifest(root: Path) -> list[str]:
    """Regenerate the checksums. Labels, notes and runs already in the manifest are kept.

    Returns the ids of skills that are new and still need a label.
    """
    known = load_manifest(root) if (root / MANIFEST_NAME).is_file() else {}
    entries: dict[str, Any] = {}
    unlabelled: list[str] = []
    for skill in discover_skills(root):
        files = hash_files(skill.path)
        previous = known.get(skill.skill_id)
        if previous is None:
            unlabelled.append(skill.skill_id)
            runs = [{"script": script, "args": []} for script in _helper_paths(skill)]
        else:
            runs = [{"script": run.script, "args": list(run.args)} for run in previous.runs]
        entry: dict[str, Any] = {
            "label": previous.label if previous else UNLABELLED,
            "runs": runs,
            "tree_digest": tree_digest(files),
            "files": [item.model_dump(mode="json") for item in files],
        }
        if previous is not None and previous.note:
            entry["note"] = previous.note
        entries[skill.skill_id] = entry
    document = {"version": MANIFEST_VERSION, "skills": entries}
    text = json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    (root / MANIFEST_NAME).write_text(text, encoding="utf-8")
    return unlabelled


def verify_manifest(root: Path) -> list[str]:
    """Compare the corpus on disk with its manifest. An empty list means it verifies."""
    manifest = load_manifest(root)
    on_disk = {skill.skill_id: skill for skill in discover_skills(root)}
    problems = [
        f"{skill_id}: on disk but not in the manifest"
        for skill_id in on_disk.keys() - manifest.keys()
    ]
    for skill_id, expected in manifest.items():
        skill = on_disk.get(skill_id)
        if skill is None:
            problems.append(f"{skill_id}: in the manifest but not on disk")
            continue
        if expected.label not in LABELS:
            problems.append(f"{skill_id}: label must be one of {', '.join(LABELS)}")
        helpers = set(_helper_paths(skill))
        scripted = {run.script for run in expected.runs}
        problems += [
            f"{skill_id}: run names a missing helper {name}" for name in scripted - helpers
        ]
        problems += [
            f"{skill_id}: helper {name} has no scripted run" for name in helpers - scripted
        ]
        recorded = {item.path: item for item in expected.files}
        actual = {item.path: item for item in hash_files(skill.path)}
        problems += [f"{skill_id}: missing file {path}" for path in recorded.keys() - actual.keys()]
        problems += [
            f"{skill_id}: unexpected file {path}" for path in actual.keys() - recorded.keys()
        ]
        problems += [
            f"{skill_id}: modified file {path}"
            for path in recorded.keys() & actual.keys()
            if recorded[path] != actual[path]
        ]
        if expected.tree_digest != tree_digest(list(expected.files)):
            problems.append(f"{skill_id}: tree_digest does not match the listed files")
    return sorted(problems)


def run_corpus(root: Path, *, scoped: bool = False, timeout: float = 30.0) -> list[CorpusRunResult]:
    """Run every scripted helper of every corpus skill, in manifest order."""
    manifest = load_manifest(root)
    on_disk = {skill.skill_id: skill for skill in discover_skills(root)}
    results: list[CorpusRunResult] = []
    for skill_id in sorted(manifest):
        entry, skill = manifest[skill_id], on_disk[skill_id]
        for run in entry.runs:
            script = skill.path / run.script
            if scoped:
                inside = run_script_scoped(skill, script, run.args, timeout)
                results.append(CorpusRunResult(skill_id, entry.label, run, inside.result, inside))
            else:
                plain = run_script(skill, script, run.args, timeout)
                results.append(CorpusRunResult(skill_id, entry.label, run, plain, None))
    return results
